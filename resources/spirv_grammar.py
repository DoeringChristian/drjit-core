#!/usr/bin/env python3
#
# Generates "spirv_grammar.h", the instruction and operand tables of the
# SPIR-V assembler of the Vulkan backend (src/vulkan_asm.cpp), from the
# machine-readable grammar in SPIRV-Headers:
#
#   python3 spirv_grammar.py <path to SPIRV-Headers>

import json
import os
import subprocess
import sys

# Extended instruction sets: name in OpExtInstImport -> grammar file
EXT_INST_SETS = {
    'GLSL.std.450': 'extinst.glsl.std.450.grammar.json',
}

QUANTIFIERS = {None: 'SpirvOne', '?': 'SpirvOptional', '*': 'SpirvVariadic'}


def main():
    root = sys.argv[1]
    unified = os.path.join(root, 'include', 'spirv', 'unified1')
    with open(os.path.join(unified, 'spirv.core.grammar.json')) as f:
        core = json.load(f)
    try:
        rev = subprocess.check_output(['git', '-C', root, 'describe', '--tags',
                                       '--always'], text=True).strip()
    except Exception:
        rev = 'unknown revision'

    kinds = core['operand_kinds']
    kind_index = {k['kind']: i for i, k in enumerate(kinds)}

    # Operand lists of instructions and enumerant parameters, deduplicated
    operands, operand_lists = [], {}

    def operand_list(ops):
        key = tuple((kind_index[o['kind']], o.get('quantifier')) for o in ops)
        if not key:
            return 0, 0
        if key not in operand_lists:
            operand_lists[key] = len(operands)
            operands.extend(key)
        return operand_lists[key], len(key)

    instructions = []
    for inst in core['instructions']:
        offset, count = operand_list(inst.get('operands', []))
        for name in [inst['opname']] + inst.get('aliases', []):
            instructions.append((name, inst['opcode'], offset, count))
    instructions.sort()

    enumerants, enum_ranges = [], []
    for k in kinds:
        begin = len(enumerants)
        entries = []
        for e in k.get('enumerants', []):
            value = e['value']
            if isinstance(value, str):
                value = int(value, 0)
            offset, count = operand_list(e.get('parameters', []))
            for name in [e['enumerant']] + e.get('aliases', []):
                entries.append((name, value, offset, count))
        entries.sort()
        enumerants.extend(entries)
        enum_ranges.append((begin, len(enumerants)))

    ext_sets = []
    for set_name, fname in EXT_INST_SETS.items():
        with open(os.path.join(unified, fname)) as f:
            grammar = json.load(f)
        ext_sets.append((set_name, sorted(
            (i['opname'], i['opcode']) for i in grammar['instructions'])))

    assert len(kinds) < 256 and len(operands) < 65536
    assert len(enumerants) < 65536

    o = []
    o.append('// This file was automatically generated by "spirv_grammar.py" '
             'from SPIRV-Headers')
    o.append('// (%s, SPIR-V %i.%i revision %i)' % (
        rev, core['major_version'], core['minor_version'], core['revision']))
    o.append('')
    o.append('#pragma once')
    o.append('')
    o.append('#include <stdint.h>')
    o.append('')
    o.append('enum SpirvCategory : uint8_t { SpirvId, SpirvLiteral, '
             'SpirvComposite, SpirvValueEnum, SpirvBitEnum };')
    o.append('enum SpirvQuantifier : uint8_t { SpirvOne, SpirvOptional, '
             'SpirvVariadic };')
    o.append('')
    o.append('enum SpirvKind : uint8_t {')
    for k in kinds:
        o.append('    SpirvKind%s,' % k['kind'])
    o.append('};')
    o.append('')
    o.append('struct SpirvKindInfo { const char *name; SpirvCategory category; '
             'uint16_t enum_begin, enum_end; };')
    o.append('struct SpirvOperand { SpirvKind kind; SpirvQuantifier quantifier; };')
    o.append('struct SpirvInstruction { const char *name; uint16_t opcode, '
             'operand_offset, operand_count; };')
    o.append('struct SpirvEnumerant { const char *name; uint32_t value; '
             'uint16_t param_offset, param_count; };')
    o.append('struct SpirvExtInst { const char *name; uint32_t opcode; };')
    o.append('struct SpirvExtInstSet { const char *name; '
             'const SpirvExtInst *insts; uint32_t count; };')
    o.append('')

    o.append('static const SpirvKindInfo spirv_kinds[] = {')
    for k, (b, e) in zip(kinds, enum_ranges):
        o.append('    { "%s", Spirv%s, %i, %i },' % (k['kind'], k['category'], b, e))
    o.append('};')
    o.append('')

    o.append('static const SpirvOperand spirv_operands[] = {')
    for i in range(0, len(operands), 4):
        o.append('    ' + ' '.join('{ SpirvKind%s, %s },' % (
            kinds[k]['kind'], QUANTIFIERS[q]) for k, q in operands[i:i+4]))
    o.append('};')
    o.append('')

    o.append('/// Sorted by name')
    o.append('static const SpirvInstruction spirv_instructions[] = {')
    for name, opcode, offset, count in instructions:
        o.append('    { "%s", %i, %i, %i },' % (name, opcode, offset, count))
    o.append('};')
    o.append('')

    o.append('/// Sorted by name within the range of each kind')
    o.append('static const SpirvEnumerant spirv_enumerants[] = {')
    for name, value, offset, count in enumerants:
        o.append('    { "%s", 0x%x, %i, %i },' % (name, value, offset, count))
    o.append('};')
    o.append('')

    for idx, (set_name, insts) in enumerate(ext_sets):
        o.append('static const SpirvExtInst spirv_ext_inst_%i[] = {' % idx)
        for name, opcode in insts:
            o.append('    { "%s", %i },' % (name, opcode))
        o.append('};')
        o.append('')
    o.append('static const SpirvExtInstSet spirv_ext_inst_sets[] = {')
    for idx, (set_name, insts) in enumerate(ext_sets):
        o.append('    { "%s", spirv_ext_inst_%i, %i },' % (set_name, idx, len(insts)))
    o.append('};')

    out = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                       'spirv_grammar.h')
    with open(out, 'w') as f:
        f.write('\n'.join(o) + '\n')


if __name__ == '__main__':
    main()
